#!/usr/bin/env python3
"""Create and publish Fidret Lab pieces as static HTML using the standard library."""

from __future__ import annotations

import argparse
import html
import json
import re
from datetime import date, datetime, timezone
from pathlib import Path
from string import Template
from urllib.parse import urlsplit
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = "https://fidret.com"
MARKER = "<!-- Generated by scripts/lab.py; edit lab/pieces/ and templates/lab/. -->\n"
KINDS = {
    "simulation": "Simulation",
    "prototype": "Prototype",
    "technical-note": "Technical note",
    "architecture": "Architecture note",
}
SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")
MONTHS = ("January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December")
FIELDS = {
    "schema_version", "slug", "title", "kind", "status", "authors", "created",
    "published", "updated", "summary", "question", "approach", "takeaways",
    "limits", "next_steps", "resources", "media", "snippets",
}


def today_utc() -> date:
    return datetime.now(timezone.utc).date()


def local_path(root: Path, path: Path) -> Path:
    """Keep generated writes and source reads inside this checkout without symlinks."""
    base, target = root.absolute(), path.absolute()
    if not target.is_relative_to(base):
        raise ValueError(f"{path}: path leaves the repository")
    current = base
    for part in ("", *target.relative_to(base).parts):
        if part:
            current /= part
        if current.is_symlink():
            raise ValueError(f"{current}: symlinks are not permitted in Lab source or output paths")
    if not target.resolve().is_relative_to(base.resolve()):
        raise ValueError(f"{path}: resolved path leaves the repository")
    return target


def read_json(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ValueError(f"{path}: {error}") from error


def safe_url(value) -> bool:
    if not isinstance(value, str) or not value:
        return False
    parsed = urlsplit(value)
    return ((parsed.scheme == "https" and bool(parsed.netloc) and not parsed.username)
            or (value.startswith("/") and not value.startswith("//") and not parsed.scheme))


def author_registry(root: Path) -> dict:
    authors = read_json(local_path(root, root / "lab/authors.json"))
    if not isinstance(authors, dict) or not authors:
        raise ValueError("lab/authors.json: expected a non-empty author registry")
    for key, author in authors.items():
        if (not SLUG.fullmatch(key) or not isinstance(author, dict)
                or not isinstance(author.get("name"), str) or not author["name"].strip()
                or not safe_url(author.get("url"))):
            raise ValueError(f"lab/authors.json: invalid author {key!r}")
    return authors


def iso_date(value, field: str) -> date:
    if not isinstance(value, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
        raise ValueError(f"{field}: use YYYY-MM-DD")
    try:
        result = date.fromisoformat(value)
    except ValueError as error:
        raise ValueError(f"{field}: invalid date") from error
    if result > today_utc():
        raise ValueError(f"{field}: future dates are not supported; leave publication unset while drafting")
    return result


def validate_piece(piece, slug: str, authors: dict, root: Path) -> None:
    def require(condition, message):
        if not condition:
            raise ValueError(f"lab/pieces/{slug}.json: {message}")

    require(isinstance(piece, dict), "expected an object")
    require(not set(piece) - FIELDS, f"unknown fields: {sorted(set(piece) - FIELDS)}")
    require(piece.get("schema_version") == 1, "schema_version must be 1")
    require(bool(SLUG.fullmatch(slug)) and piece.get("slug") == slug, "slug must match the safe filename")
    require(piece.get("kind") in KINDS, f"kind must be one of {', '.join(KINDS)}")
    require(piece.get("status") in {"draft", "published"}, "status must be draft or published")
    selected = piece.get("authors")
    require(isinstance(selected, list) and bool(selected), "choose at least one author explicitly")
    require(all(isinstance(a, str) and a in authors for a in selected), "authors must use registered IDs")
    require(len(set(selected)) == len(selected), "author IDs must be unique")
    for field in ("title", "summary", "question"):
        require(isinstance(piece.get(field), str), f"{field} must be text")
    require(bool(piece["title"].strip()), "title cannot be empty")
    created = iso_date(piece.get("created"), f"{slug}.created")
    updated = iso_date(piece.get("updated"), f"{slug}.updated")
    require(created <= updated, "updated cannot precede created")
    for field in ("approach", "takeaways", "limits", "next_steps"):
        require(isinstance(piece.get(field), list)
                and all(isinstance(v, str) and v.strip() for v in piece[field]),
                f"{field} must be a list of non-empty text items")
    if piece["status"] == "published":
        published = iso_date(piece.get("published"), f"{slug}.published")
        require(created <= published <= updated, "publication date must lie between created and updated")
        for field in ("summary", "question", "approach", "takeaways", "limits", "next_steps"):
            require(bool(piece[field].strip() if isinstance(piece[field], str) else piece[field]),
                    f"complete {field} before publishing")
    elif piece.get("published") is not None:
        iso_date(piece["published"], f"{slug}.published")
    resources = piece.get("resources", [])
    require(isinstance(resources, list), "resources must be a list")
    for resource in resources:
        require(isinstance(resource, dict) and set(resource) == {"label", "url"}, "resource needs label and url")
        require(isinstance(resource["label"], str) and bool(resource["label"].strip())
                and safe_url(resource["url"]), "resource needs a label and an HTTPS or local URL")
    media = piece.get("media", [])
    require(isinstance(media, list), "media must be a list")
    for figure in media:
        require(isinstance(figure, dict) and set(figure) == {"src", "alt", "caption", "width", "height"},
                "media needs src, alt, caption, width, and height")
        require(all(isinstance(figure[k], str) and figure[k].strip() for k in ("src", "alt", "caption")),
                "media descriptions cannot be empty")
        path = (root / "website" / figure["src"].lstrip("/")).resolve()
        require(figure["src"].startswith("/lab-assets/")
                and path.is_relative_to((root / "website/lab-assets").resolve())
                and path.is_file() and path.suffix.lower() in {".svg", ".png", ".jpg", ".jpeg", ".webp", ".gif"},
                "media must reference an existing image under /lab-assets/")
        require(all(type(figure[k]) is int and figure[k] > 0 for k in ("width", "height")),
                "media dimensions must be positive integers")
    snippets = piece.get("snippets", [])
    require(isinstance(snippets, list), "snippets must be a list")
    for snippet in snippets:
        require(isinstance(snippet, dict) and set(snippet) == {"title", "language", "code"}
                and all(isinstance(snippet[k], str) and snippet[k].strip() for k in snippet),
                "snippets need a title, language, and code")


def load_pieces(root: Path, authors: dict) -> list[dict]:
    pieces = []
    folder = local_path(root, root / "lab/pieces")
    for path in sorted(folder.glob("*.json")):
        if path.is_symlink():
            raise ValueError(f"{path}: piece sources must not be symlinks")
        piece = read_json(path)
        validate_piece(piece, path.stem, authors, root)
        pieces.append(piece)
    return pieces


def esc(value: str) -> str:
    return html.escape(value, quote=True)


def byline(ids: list[str], authors: dict) -> str:
    return " and ".join(f'<a href="{esc(authors[key]["url"])}">{esc(authors[key]["name"])}</a>' for key in ids)


def date_html(value: str) -> str:
    d = date.fromisoformat(value)
    return f'<time datetime="{value}">{d.day} {MONTHS[d.month - 1]} {d.year}</time>'


def sections(piece: dict) -> str:
    output = []
    for heading, field, style in (
        ("What this explores", "question", "text"), ("Approach", "approach", "paragraphs"),
        ("Takeaways", "takeaways", "list"), ("Limits", "limits", "list"),
        ("Next steps", "next_steps", "list"),
    ):
        value = piece[field]
        if style == "text":
            body = f"<p>{esc(value)}</p>"
        elif style == "paragraphs":
            body = "".join(f"<p>{esc(v)}</p>" for v in value)
        else:
            body = "<ul>" + "".join(f"<li>{esc(v)}</li>" for v in value) + "</ul>"
        output.append(f'<section class="lab-section"><h2>{heading}</h2>{body}</section>')
    illustrations = []
    for figure in piece.get("media", []):
        illustrations.append(f'<figure class="lab-figure"><img src="{esc(figure["src"])}" alt="{esc(figure["alt"])}" '
                      f'width="{figure["width"]}" height="{figure["height"]}" loading="lazy">'
                      f'<figcaption>{esc(figure["caption"])}</figcaption></figure>')
    for snippet in piece.get("snippets", []):
        illustrations.append(f'<figure class="lab-code"><figcaption>{esc(snippet["title"])} '
                      f'({esc(snippet["language"])})</figcaption><pre><code>{esc(snippet["code"])}</code></pre></figure>')
    output[2:2] = illustrations
    links = list(piece.get("resources", [])) + [{
        "label": "Piece source and revision history",
        "url": f'https://github.com/HadiAbouDaya/fidret/blob/main/lab/pieces/{piece["slug"]}.json',
    }]
    output.append('<section class="lab-section"><h2>Resources</h2><ul class="lab-resources">'
                  + "".join(f'<li><a href="{esc(r["url"])}">{esc(r["label"])}</a></li>' for r in links)
                  + "</ul></section>")
    return "\n".join(output)


def sitemap(root: Path, published: list[dict]) -> str:
    ns = "http://www.sitemaps.org/schemas/sitemap/0.9"
    ET.register_namespace("", ns)
    output = ET.Element(f"{{{ns}}}urlset")
    source = local_path(root, root / "website/sitemap.xml")
    if source.exists():
        try:
            old = ET.parse(source).getroot()
        except ET.ParseError as error:
            raise ValueError("website/sitemap.xml: invalid XML") from error
        for item in old:
            loc = item.find(f"{{{ns}}}loc")
            if loc is not None and loc.text:
                path = urlsplit(loc.text).path
                if path.rstrip("/") != "/lab" and not path.startswith("/lab/"):
                    output.append(item)
    if not len(output):
        item = ET.SubElement(output, f"{{{ns}}}url")
        ET.SubElement(item, f"{{{ns}}}loc").text = ORIGIN + "/"
    for url in [ORIGIN + "/lab/"] + [f'{ORIGIN}/lab/{p["slug"]}/' for p in published]:
        item = ET.SubElement(output, f"{{{ns}}}url")
        ET.SubElement(item, f"{{{ns}}}loc").text = url
    ET.indent(output, space="  ")
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(output, encoding="unicode") + "\n"


def render(root: Path) -> tuple[dict[Path, str], int, int]:
    authors = author_registry(root)
    pieces = load_pieces(root, authors)
    published = sorted((p for p in pieces if p["status"] == "published"),
                       key=lambda p: (p["published"], p["slug"]), reverse=True)
    try:
        templates = {name: Template(local_path(root, root / f"templates/lab/{name}.html").read_text(encoding="utf-8"))
                     for name in ("base", "index", "piece")}
    except OSError as error:
        raise ValueError(f"Lab templates unavailable: {error}") from error

    def page(title, description, url, content):
        return MARKER + templates["base"].substitute(title=esc(title), description=esc(description),
                                                    canonical=esc(url), content=content)

    entries = []
    for p in published:
        entries.append('<article class="lab-entry">'
                       f'<p class="lab-entry-meta">{KINDS[p["kind"]]} — {date_html(p["published"])}</p>'
                       f'<h2 class="lab-entry-title"><a href="/lab/{p["slug"]}/">{esc(p["title"])}</a></h2>'
                       f'<p class="lab-entry-summary">{esc(p["summary"])}</p>'
                       f'<p class="lab-entry-byline">By {byline(p["authors"], authors)}</p></article>')
    collection = ('<div class="lab-list">' + "\n".join(entries) + "</div>" if entries else
                  '<div class="lab-empty"><p>Our first pieces will appear here.</p>'
                  '<p>Each will share a question, an approach, takeaways, and the next things to explore.</p>'
                  '<a href="https://github.com/HadiAbouDaya/fidret">Follow the project on GitHub</a></div>')
    contributors = "<ul>" + "".join(f"<li>{byline([key], authors)}</li>" for key in authors) + "</ul>"
    content = templates["index"].substitute(entries=collection, contributors=contributors)
    output = {root / "website/lab/index.html": page(
        "Fidret Lab — Simulations, prototypes and technical notes",
        "A shared space for Hadi Abou Daya and Elie Azoury to explore physical AI through simulations, prototypes and technical notes.",
        ORIGIN + "/lab/", content)}
    for p in published:
        dates = "Published " + date_html(p["published"])
        if p["updated"] != p["published"]:
            dates += ". Updated " + date_html(p["updated"])
        content = templates["piece"].substitute(
            kind_label=KINDS[p["kind"]], piece_title=esc(p["title"]), summary=esc(p["summary"]),
            byline="By " + byline(p["authors"], authors), dates=dates, sections=sections(p))
        output[root / f'website/lab/{p["slug"]}/index.html'] = page(
            p["title"] + " — Fidret Lab", p["summary"], f'{ORIGIN}/lab/{p["slug"]}/', content)
    output[root / "website/sitemap.xml"] = sitemap(root, published)
    return output, len(published), len(pieces) - len(published)


def build(root: Path, check=False) -> tuple[int, int]:
    local_path(root, root / "website/lab")
    local_path(root, root / "website/sitemap.xml")
    try:
        output, published, drafts = render(root)
    except (KeyError, TypeError, ValueError) as error:
        raise ValueError(f"Lab source or template error: {error}") from error
    existing = set((root / "website/lab").rglob("*.html"))
    managed = {p for p in output if p.suffix == ".html"}
    for path in set(output) | existing:
        local_path(root, path)
    for path in existing:
        if not path.read_text(encoding="utf-8").startswith(MARKER):
            raise ValueError(f"{path}: unmanaged file in generated Lab directory; preserve it before building")
    stale = existing - managed
    changed = [p for p, text in output.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    if check and (stale or changed):
        names = ", ".join(str(p.relative_to(root)) for p in sorted(stale | set(changed)))
        raise ValueError(f"Generated Lab pages are stale ({names}); run python3 scripts/lab.py build")
    if not check:
        for path in stale:
            path.unlink()
            if path.parent != root / "website/lab":
                try:
                    path.parent.rmdir()
                except OSError:
                    pass
        for path, text in output.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    return published, drafts


def new_piece(root: Path, slug: str, title: str, kind: str, authors: list[str]) -> Path:
    if not SLUG.fullmatch(slug):
        raise ValueError("Use a lowercase slug with words separated by hyphens")
    path = local_path(root, root / f"lab/pieces/{slug}.json")
    if path.exists():
        raise ValueError(f"{path}: already exists; the existing piece was preserved")
    piece = read_json(local_path(root, root / "lab/TEMPLATE.json"))
    today = today_utc().isoformat()
    piece.update(slug=slug, title=title, kind=kind, authors=authors,
                 created=today, updated=today)
    validate_piece(piece, slug, author_registry(root), root)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8") as stream:
        stream.write(json.dumps(piece, indent=2, ensure_ascii=False) + "\n")
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    new = commands.add_parser("new", help="Create an incomplete draft with explicit bylines")
    new.add_argument("slug")
    new.add_argument("--title", required=True)
    new.add_argument("--kind", choices=KINDS, default="technical-note")
    new.add_argument("--author", action="append", required=True)
    commands.add_parser("build", help="Generate the static Lab and update its sitemap entries")
    commands.add_parser("check", help="Validate sources and ensure generated pages are current")
    args = parser.parse_args()
    try:
        if args.command == "new":
            path = new_piece(ROOT, args.slug, args.title, args.kind, args.author)
            print(f"Created draft {path.relative_to(ROOT)}.")
            print("Drafts stay off the website; source files in this GitHub repository are public.")
        else:
            published, drafts = build(ROOT, check=args.command == "check")
            print(f"Lab OK: {published} published, {drafts} drafts; static pages {'verified' if args.command == 'check' else 'generated'}.")
    except (OSError, ValueError) as error:
        print(f"Lab validation failed: {error}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
